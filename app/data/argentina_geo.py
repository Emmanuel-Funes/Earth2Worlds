def obtener_provincias() -> List[str]:
    """Devuelve la lista ordenada de las 23 provincias argentinas + CABA (con San Luis destacada primero)."""
    todas = sorted(ARGENTINA_GEO.keys())
    if "San Luis" in todas:
        todas.remove("San Luis")
        todas.insert(0, "San Luis")
    return todas


def obtener_localidades_por_provincia(provincia: str) -> List[Dict[str, str]]:
    """Devuelve las localidades y códigos postales de una provincia argentina."""
    if not provincia:
        return []
    clave_exacta = next(
        (k for k in ARGENTINA_GEO.keys() if k.lower() == provincia.strip().lower()),
        None,
    )
    if not clave_exacta:
        return []
    return ARGENTINA_GEO[clave_exacta]
